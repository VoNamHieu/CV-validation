/**
 * A complete fake candidate, for test builds only.
 *
 * Testing the apply agent used to require the whole upstream chain: sign into
 * the web app, sync a profile, optimise a CV so a tailored PDF exists, then
 * launch a batch — several minutes of setup before the agent does the one thing
 * under test, and every ATS bug found that way cost the same setup again. This
 * module lets `npm run build:test` produce a bundle that seeds itself.
 *
 * A normal build never reads this file: build.mjs resolves the import to
 * fixtures/noop.js instead, so the fake candidate is absent from the production
 * bundle by construction rather than by dead-code elimination (noop.js explains
 * why that distinction turned out to matter).
 *
 * Three rules this file keeps:
 *
 *   1. It NEVER overwrites real data. Seeding fills empty storage slots only, so
 *      loading a test build over a signed-in profile changes nothing.
 *   2. Every value is recognisably fake at a glance — @example.invalid is a
 *      reserved TLD that cannot resolve, and the name says TEST. A screenshot of
 *      a form filled from here should be impossible to mistake for a real
 *      application.
 *   3. The values are the ones REAL forms demand, not a minimal stub: the gaps
 *      measured on Mondelez (postal code, notice period, GPA, work
 *      authorisation, sponsorship, expected salary) are all populated, because a
 *      fixture that leaves them blank cannot exercise the steps they block.
 */

